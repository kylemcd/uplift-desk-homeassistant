import { describe, expect, it } from "vitest"
import { commandToOpcode, decodeNotifications, encodeCommand, NotificationStreamDecoder } from "../src/index.js"

describe("UPLIFT packets", () => {
  it.each([
    [{ type: "wake" } as const, [0xf1, 0xf1, 0x00, 0x00, 0x00, 0x7e]],
    [{ type: "move_up" } as const, [0xf1, 0xf1, 0x01, 0x00, 0x01, 0x7e]],
    [{ type: "move_down" } as const, [0xf1, 0xf1, 0x02, 0x00, 0x02, 0x7e]],
    [{ type: "stop" } as const, [0xf1, 0xf1, 0x2b, 0x00, 0x2b, 0x7e]],
    [{ type: "save_preset", preset: 1 } as const, [0xf1, 0xf1, 0x03, 0x00, 0x03, 0x7e]],
    [{ type: "save_preset", preset: 2 } as const, [0xf1, 0xf1, 0x04, 0x00, 0x04, 0x7e]],
    [{ type: "recall_preset", preset: 1 } as const, [0xf1, 0xf1, 0x05, 0x00, 0x05, 0x7e]],
    [{ type: "recall_preset", preset: 2 } as const, [0xf1, 0xf1, 0x06, 0x00, 0x06, 0x7e]],
    [{ type: "request_height_limits" } as const, [0xf1, 0xf1, 0x07, 0x00, 0x07, 0x7e]],
    [{ type: "request_units" } as const, [0xf1, 0xf1, 0x0e, 0x00, 0x0e, 0x7e]],
    [{ type: "reset" } as const, [0xf1, 0xf1, 0xfe, 0x00, 0xfe, 0x7e]],
    [{ type: "set_maximum_height", heightMm: 1372 } as const, [0xf1, 0xf1, 0x11, 0x02, 0x05, 0x5c, 0x74, 0x7e]],
    [{ type: "move_to_height", height: 1422 } as const, [0xf1, 0xf1, 0x1b, 0x02, 0x05, 0x8e, 0xb0, 0x7e]],
    [{ type: "set_units", unit: "centimeters" } as const, [0xf1, 0xf1, 0x0e, 0x01, 0x00, 0x0f, 0x7e]],
    [{ type: "set_units", unit: "inches" } as const, [0xf1, 0xf1, 0x0e, 0x01, 0x01, 0x10, 0x7e]],
    [{ type: "set_touch_mode", mode: "one_touch" } as const, [0xf1, 0xf1, 0x19, 0x01, 0x00, 0x1a, 0x7e]],
    [{ type: "set_touch_mode", mode: "constant_touch" } as const, [0xf1, 0xf1, 0x19, 0x01, 0x01, 0x1b, 0x7e]],
    [{ type: "set_calibration_offset", offset: 0x1234 } as const, [0xf1, 0xf1, 0x10, 0x02, 0x12, 0x34, 0x58, 0x7e]],
    [{ type: "set_current_height_as_limit", limit: "maximum" } as const, [0xf1, 0xf1, 0x21, 0x00, 0x21, 0x7e]],
    [{ type: "set_current_height_as_limit", limit: "minimum" } as const, [0xf1, 0xf1, 0x22, 0x00, 0x22, 0x7e]],
    [{ type: "clear_height_limit", limit: "maximum" } as const, [0xf1, 0xf1, 0x23, 0x01, 0x01, 0x25, 0x7e]],
    [{ type: "clear_height_limit", limit: "minimum" } as const, [0xf1, 0xf1, 0x23, 0x01, 0x02, 0x26, 0x7e]],
  ])("encodes %#", (command, expected) => {
    const value = commandToOpcode(command)
    expect([...encodeCommand(value.opcode, value.payload)]).toEqual(expected)
  })

  it("extracts valid notifications and skips invalid data", () => {
    const data = Uint8Array.of(0x99, 0xf2, 0xf2, 0x0e, 0x01, 0x01, 0x10, 0x7e, 0xf2, 0xf2, 0x01, 0x00, 0xff, 0x7e)
    expect(decodeNotifications(data)).toEqual([{ opcode: 0x0e, payload: Uint8Array.of(1), checksum: 0x10 }])
  })

  it("retains fragmented notifications and decodes concatenated packets", () => {
    const decoder = new NotificationStreamDecoder()
    expect(decoder.push(Uint8Array.of(0x99, 0xf2, 0xf2, 0x0e))).toEqual([])
    expect(decoder.push(Uint8Array.of(0x01, 0x01, 0x10, 0x7e, 0xf2, 0xf2, 0x04, 0x00, 0x04, 0x7e))).toEqual([
      { opcode: 0x0e, payload: Uint8Array.of(1), checksum: 0x10 },
      { opcode: 0x04, payload: new Uint8Array(), checksum: 0x04 },
    ])
  })

  it("rejects uint16 overflow", () => {
    expect(() => commandToOpcode({ type: "move_to_height", height: 65_536 })).toThrow(RangeError)
  })
})
